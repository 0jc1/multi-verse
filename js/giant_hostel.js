/* APEVERSE — giant_hostel.js : photo-accurate skin for Giant Hostel (Chiang Mai).
   Built from ZtonedApe's photos of the real shopfront (assets/reference/giant_hostel/):
   the magenta GIANT HOSTEL banner + MacBook display above the glass shopfront, the dark
   metal canopy, the glass door with Christmas decals + WELCOME mat, the green neon leaf
   in the side window, the Buds / Organic High Quality lightbox on the canopy, the red
   "no under 20" board by the door, brick-slip base walls, black granite tables and the
   Mr. Mechanic blade sign next door. Textures are data URIs (AV.TEX_GH) generated by
   tools/build_giant_hostel_assets.py, so they also work from file://.
   world_chiang_mai.js calls AV.buildGiantHostel() after building the base hostel. */
'use strict';
(function (AV) {
  if (!window.AV) window.AV = AV;
  const loaded = {};
  function tex(key, rep) {
    if (loaded[key]) return loaded[key];
    const t = new THREE.TextureLoader().load(AV.TEX_GH[key]);
    t.encoding = THREE.sRGBEncoding; t.anisotropy = 4;
    t.wrapS = t.wrapT = rep ? THREE.RepeatWrapping : THREE.ClampToEdgeWrapping;
    return loaded[key] = t;
  }
  /* one MeshStandardMaterial per use (each with its own repeat), textures cached by key */
  function planeMat(key, o) {
    o = o || {};
    const m = new THREE.MeshStandardMaterial({
      map: tex(key, o.rep), roughness: o.rough != null ? o.rough : .82, metalness: o.metal || 0,
      transparent: !!o.transparent, opacity: o.opacity != null ? o.opacity : 1, side: o.side || THREE.FrontSide
    });
    if (o.rep && o.repeat) m.map.repeat.set(o.repeat[0], o.repeat[1]);
    if (o.emissive) { m.emissive = new THREE.Color(0xffffff); m.emissiveMap = m.map; m.emissiveIntensity = o.emissive; m.userData.emBase = o.emissive; m.userData.emNight = o.emNight || 0 }
    m.userData.lin = 1;
    return m;
  }
  /* textured plane at x/y/z facing yaw (yaw 0 = +z, PI = -z ...), correct aspect ratio by w/h */
  function plane(grp, mat, x, y, z, w, h, yaw) {
    const p = new THREE.Mesh(AV.G.pln, mat);
    p.position.set(x, y, z); p.scale.set(w, h, 1); p.rotation.y = yaw;
    grp.add(p); return p;
  }
  /* Av = { ctx, H, MT, M, box, grp, hb, B } — handed over by world_chiang_mai after the base hostel is built.
     Every plane's w/h is chosen to match its texture's pixel aspect (banner 3:1, door 1:2, window 2:1,
     buds 2:1, display 2:1, age 1:2, granite 1:1, mat 2:1, mechanic 1:1) at real-metre scale. */
  AV.buildGiantHostel = function (Av) {
    const { ctx, H, MT, box, grp } = Av, hb = Av.hb;
    const cols = ctx.cols, circles = ctx.circles, upd = ctx.upd;
    const G = AV.G, BG = AV.kit.BG;
    const nightMats = [];
    const facingStreet = Math.PI;   // the hostel's front wall faces north (-z), so front textures yaw PI

    /* ---- 1. banner + MacBook display above the shopfront ---- */
    /* banner texture is 2400x760 px = 3.16:1; drawn 9.0 m x 2.85 m on the wall */
    plane(grp, planeMat('banner', { rough: .9 }), 25, 5.1, H.z0 + .01, 9.0, 2.85, facingStreet);
    /* display texture is 512x256 = 2:1; drawn 2.9 m x 1.45 m under the banner (the MacBook screen) */
    plane(grp, planeMat('display', { rough: .35, emissive: .55, emNight: .5 }), 25, 2.5, H.z0 + .02, 2.9, 1.45, facingStreet)
      .material && nightMats.push(grp.children[grp.children.length - 1].material);

    /* ---- 2. dark metal canopy over the terrace ---- */
    box(hb, MT.shiny, 0x53555c, H.x0 - .7, H.x1 + .7, 3.18, 3.3, 47.1, 52.3);            // fascia rail
    box(hb, MT.shiny, 0x6a6d75, H.x0 - .7, H.x1 + .7, 3.52, 3.62, 47.1, 52.3);           // back rail on the wall
    box(hb, MT.shiny, 0x3d3f45, H.x0 - .7, H.x0 - .5, 3.1, 3.3, 47.2, 52.2);             // side trim W
    box(hb, MT.shiny, 0x3d3f45, H.x1 + .5, H.x1 + .7, 3.1, 3.3, 47.2, 52.2);             // side trim E
    { const corr = new THREE.Mesh(BG.box, MT.roof); corr.position.set((H.x0 + H.x1) / 2, 3.62, 49.75); corr.scale.set(H.x1 - H.x0 + 1.6, .07, 5.3); grp.add(corr) }   // corrugated deck
    /* Buds / Organic High Quality lightbox on the canopy, west end (texture 2:1, drawn 2.1 x 1.05) */
    box(hb, MT.shiny, 0x2e2e30, 8.35, 10.55, 2.72, 3.3, 47.5, 47.68);
    { const bm = planeMat('buds', { rough: .5, emissive: .5, emNight: 1.15 });
      plane(grp, bm, 9.45, 3.0, 47.465, 2.1, 1.05, facingStreet); nightMats.push(bm) }
    for (const cx of [8.55, 10.35]) box(hb, MT.shiny, 0x4a4a4e, cx - .03, cx + .03, 2.3, 2.75, 47.55, 47.61);   // hangers
    { const l = new THREE.PointLight(0xfff2d8, 0, 6); l.position.set(9.45, 3.0, 47.2); grp.add(l); upd.push(() => { l.intensity = (AV.nightK || 0) * .9 }) }
    circles.push([9.45, 47.6, .25]);

    /* ---- 3. glass door leaf (Christmas decals + PUSH) + WELCOME mat ---- */
    /* door texture is 512x1024 = 1:2; drawn 1.15 m x 2.3 m in the entrance gap */
    plane(grp, planeMat('door', { rough: .3, metal: .15 }), 15.5, 1.22, H.z0 + .045, 1.15, 2.3, facingStreet);
    { /* mat texture is 512x256 = 2:1; drawn 1.2 m x 0.6 m on the floor */
      const mm = planeMat('mat', { rough: .95 });
      const mp = plane(grp, mm, 15.5, .075, 51.15, 1.2, .6, facingStreet);
      mp.rotation.x = -Math.PI / 2; mp.rotation.z = Math.PI; mp.rotation.order = 'YXZ' }

    /* ---- 4. side window with the green neon leaf (texture 2:1, drawn 2.5 x 1.25) ---- */
    { const swm = planeMat('side_window', { rough: .35, emissive: .5, emNight: .55 });
      plane(grp, swm, 13.1, 1.6, H.z0 + .035, 2.5, 1.25, facingStreet); nightMats.push(swm) }

    /* ---- 5. red "no under 20" board by the door (east pier; texture 1:2, drawn 0.6 x 1.2) ---- */
    plane(grp, planeMat('age', { rough: .8 }), H.x1 - .015, 1.5, 55.2, .6, 1.2, Math.PI / 2);

    /* ---- 6. brick-slip base walls, front + back (seamless tile, one repeat per 3.6 m) ---- */
    { const bf = planeMat('brick', { rep: true, repeat: [6.8, 1], rough: .92 });
      plane(grp, bf, (H.x0 + H.x1) / 2, .375, H.z0 - .045, 24.4, .75, facingStreet);
      const bb = planeMat('brick', { rep: true, repeat: [6.8, 1], rough: .92 });
      plane(grp, bb, (H.x0 + H.x1) / 2, .375, H.z1 + .045, 24.4, .75, 0) }

    /* ---- 7. black granite table tops on the terrace (texture 1:1, cylinder tops UV-wrapped) ---- */
    for (const [x, z] of [[10.9, 50.7], [24, 50.3]]) {
      const g = new THREE.Mesh(BG.cyl, planeMat('granite', { rough: .45 }));
      g.position.set(x, .755, z); g.scale.set(.52, .05, .52); grp.add(g);
    }

    /* ---- 8. Mr. Mechanic blade sign next door (texture 1:1, drawn 0.62 x 0.62) ---- */
    box(hb, MT.shiny, 0x2e2e30, 35.25, 35.4, 2.6, 3.9, 53.3, 53.42);
    { const mm = planeMat('mechanic', { rough: .5, emissive: .45, emNight: .9 });
      plane(grp, mm, 35.33, 3.25, 53.36, .62, .62, Math.PI / 2); nightMats.push(mm) }
    circles.push([35.33, 53.36, .2]);

    /* ---- shared night dimming for all photo-lit textures ---- */
    upd.push(() => { const k = AV.nightK || 0; for (const m of nightMats) m.emissiveIntensity = m.userData.emBase + k * m.userData.emNight });
    return { nightMats };
  };
})(window.AV);
